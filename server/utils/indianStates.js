function stateCodeFromName(name) {
  const target = String(name || '').trim().toLowerCase();
  if (!target) return null;
  const entry = Object.entries(STATE_CODES).find(
    ([, stateName]) => stateName.toLowerCase() === target
  );
  return entry ? entry[0] : null;
}

